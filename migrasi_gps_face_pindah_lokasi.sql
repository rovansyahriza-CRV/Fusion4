-- Pastikan ada UNIQUE constraint pada QrCodeId
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'faceData_QrCodeId_key'
    ) THEN
        ALTER TABLE "faceData" ADD CONSTRAINT "faceData_QrCodeId_key" UNIQUE ("QrCodeId");
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END $$;

ALTER TABLE "faceData" DISABLE ROW LEVEL SECURITY;

