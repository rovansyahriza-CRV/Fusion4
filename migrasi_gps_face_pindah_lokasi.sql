-- 4. FUNCTION RPC: HITUNG GPS TERDEKAT DENGAN FORMULA HAVERSINE (find_nearest_location)
DROP FUNCTION IF EXISTS find_nearest_location(NUMERIC, NUMERIC);
CREATE OR REPLACE FUNCTION find_nearest_location(
    p_lat NUMERIC,
    p_lng NUMERIC
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_rec RECORD;
    v_distance NUMERIC;
    v_in_range BOOLEAN := FALSE;
    v_message TEXT;
BEGIN
    IF p_lat IS NULL OR p_lng IS NULL THEN
        RETURN jsonb_build_object(
            'success', FALSE,
            'message', 'Koordinat GPS tidak valid.'
        );
    END IF;

    -- Cari lokasi aktif terdekat menggunakan formula Haversine (Jarak dalam Meter)
    SELECT 
        l."Id" AS id,
        l."NamaLokasi" AS namalokasi,
        l."Latitude" AS latitude,
        l."Longitude" AS longitude,
        COALESCE(l."Radius", 100)::INT AS radius,
        ROUND(
            6371000 * 2 * ASIN(
                SQRT(
                    POWER(SIN(RADIANS(p_lat - l."Latitude") / 2), 2) +
                    COS(RADIANS(p_lat)) * COS(RADIANS(l."Latitude")) *
                    POWER(SIN(RADIANS(p_lng - l."Longitude") / 2), 2)
                )
            )
        ) AS distance_meters
    INTO v_rec
    FROM "lokasiTbl" l
    WHERE UPPER(TRIM(COALESCE(l."Status", 'ACTIVE'))) = 'ACTIVE'
      AND l."Latitude" IS NOT NULL
      AND l."Longitude" IS NOT NULL
    ORDER BY distance_meters ASC
    LIMIT 1;

    IF v_rec.id IS NULL THEN
        RETURN jsonb_build_object(
            'success', FALSE,
            'message', 'Tidak ada master data lokasi aktif yang terdaftar.'
        );
    END IF;

    v_distance := v_rec.distance_meters;
    v_in_range := (v_distance <= v_rec.radius);

    IF v_in_range THEN
        v_message := '🟢 Kelompok: ' || v_rec.namalokasi || ' | Jarak: ' || v_distance || 'm | Radius: ' || v_rec.radius || 'm';
    ELSE
        v_message := '🔴 Di luar radius ' || v_rec.namalokasi || ' (' || v_distance || 'm dari batas ' || v_rec.radius || 'm)';
    END IF;

    RETURN jsonb_build_object(
        'success', TRUE,
        'location', v_rec.namalokasi,
        'distance', v_distance,
        'radius', v_rec.radius,
        'inRange', v_in_range,
        'message', v_message
    );
END;
$$;


-- 5. FUNCTION RPC: AMBIL SELURUH DATA WAJAH (get_all_face_data) UNTUK MODE 1:N
DROP FUNCTION IF EXISTS get_all_face_data();
CREATE OR REPLACE FUNCTION get_all_face_data()
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_result JSONB;
BEGIN
    SELECT COALESCE(
        jsonb_agg(
            jsonb_build_object(
                'qrCodeId', UPPER(TRIM(f."QrCodeId")),
                'nama', COALESCE(k."NamaPersonnel", f."Nama", f."QrCodeId"),
                'descriptor', f."Descriptor",
                'fotoUrl', COALESCE(f."FotoURL", k."FotoURL", '')
            )
        ),
        '[]'::JSONB
    )
    INTO v_result
    FROM "faceData" f
    LEFT JOIN "karyawanTbl" k ON UPPER(TRIM(k."QrCodeId")) = UPPER(TRIM(f."QrCodeId"))
    WHERE f."Descriptor" IS NOT NULL;

    RETURN v_result;
END;
$$;


-- 6. FUNCTION RPC: AMBIL DATA PROFIL & WAJAH 1 ORANG (get_person_face_data)
DROP FUNCTION IF EXISTS get_person_face_data(TEXT);
CREATE OR REPLACE FUNCTION get_person_face_data(p_qrcode TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_kar RECORD;
    v_face RECORD;
BEGIN
    SELECT * INTO v_kar
    FROM "karyawanTbl"
    WHERE UPPER(TRIM("QrCodeId")) = UPPER(TRIM(p_qrcode))
    LIMIT 1;

    IF v_kar."Id" IS NULL THEN
        RETURN jsonb_build_object('valid', FALSE, 'message', 'Karyawan tidak ditemukan.');
    END IF;

    SELECT * INTO v_face
    FROM "faceData"
    WHERE UPPER(TRIM("QrCodeId")) = UPPER(TRIM(p_qrcode))
    LIMIT 1;

    RETURN jsonb_build_object(
        'valid', TRUE,
        'qrCodeId', v_kar."QrCodeId",
        'nama', v_kar."NamaPersonnel",
        'kualifikasi', v_kar."Kualifikasi",
        'fotoUrl', COALESCE(v_face."FotoURL", v_kar."FotoURL", ''),
        'descriptor', v_face."Descriptor",
        'hasFaceData', (v_face."Descriptor" IS NOT NULL)
    );
END;
$$;


