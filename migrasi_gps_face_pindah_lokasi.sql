    ON CONFLICT ("QrCodeId") DO UPDATE
    SET "Nama" = EXCLUDED."Nama",
        "Descriptor" = EXCLUDED."Descriptor",
        "FotoURL" = COALESCE(NULLIF(EXCLUDED."FotoURL", ''), "faceData"."FotoURL"),
        "UpdatedAt" = NOW();

    -- Update FotoURL di karyawanTbl jika ada
    IF p_fotourl IS NOT NULL AND TRIM(p_fotourl) <> '' THEN
        UPDATE "karyawanTbl"
        SET "FotoURL" = p_fotourl
        WHERE UPPER(TRIM("QrCodeId")) = UPPER(TRIM(p_qrcode));
    END IF;

    RETURN jsonb_build_object(
        'status', 'SUKSES',
        'message', 'Data wajah untuk ' || p_nama || ' (' || UPPER(TRIM(p_qrcode)) || ') berhasil disimpan!'
    );
END;
$$;


-- 8. FUNCTION RPC: PERMOHONAN PINDAH LOKASI (submit_pindah_lokasi & get_pindah_lokasi_status)
DROP FUNCTION IF EXISTS submit_pindah_lokasi(TEXT, TEXT, TEXT, TEXT);
CREATE OR REPLACE FUNCTION submit_pindah_lokasi(
    p_qrcode TEXT,
    p_lokasi_tujuan TEXT,
    p_alasan TEXT DEFAULT '',
    p_lokasi_lama TEXT DEFAULT ''
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_nama TEXT;
    v_new_id BIGINT;
BEGIN
    SELECT "NamaPersonnel" INTO v_nama
    FROM "karyawanTbl"
    WHERE UPPER(TRIM("QrCodeId")) = UPPER(TRIM(p_qrcode))
    LIMIT 1;

    INSERT INTO "pindah_lokasi_tbl" ("qrcodeid", "nama", "lokasi_lama", "lokasi_tujuan", "alasan", "status", "created_at", "updated_at")
    VALUES (UPPER(TRIM(p_qrcode)), COALESCE(v_nama, p_qrcode), p_lokasi_lama, p_lokasi_tujuan, p_alasan, 'PENDING', NOW(), NOW())
    RETURNING "id" INTO v_new_id;

    RETURN jsonb_build_object(
        'status', 'SUKSES',
        'message', 'Permohonan pindah ke ' || p_lokasi_tujuan || ' berhasil diajukan.',
        'id', v_new_id
    );
END;
$$;

DROP FUNCTION IF EXISTS get_pindah_lokasi_status(TEXT);
CREATE OR REPLACE FUNCTION get_pindah_lokasi_status(p_qrcode TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_rec RECORD;
BEGIN
    SELECT * INTO v_rec
    FROM "pindah_lokasi_tbl"
    WHERE UPPER(TRIM("qrcodeid")) = UPPER(TRIM(p_qrcode))
      AND "created_at" >= CURRENT_DATE
    ORDER BY "id" DESC
    LIMIT 1;

    IF v_rec.id IS NULL THEN
        RETURN jsonb_build_object('hasRequest', FALSE);
    END IF;

    RETURN jsonb_build_object(
        'hasRequest', TRUE,
        'status', v_rec.status,
        'lokasiTujuan', v_rec.lokasi_tujuan,
        'createdAt', v_rec.created_at
    );
END;
$$;
