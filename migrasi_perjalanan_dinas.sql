DO $patch$
DECLARE
    d text;
    a text;
BEGIN
    -- 8a. process_approval_action: PD dialihkan ke proses_perjalanan_dinas_inti.
    d := pg_get_functiondef('public.process_approval_action(bigint,text,text,text)'::regprocedure);
    IF position('proses_perjalanan_dinas_inti' IN d) = 0 THEN
        a := E'    SELECT "NamaPersonnel", "Kualifikasi", TRIM("Author") as author_code\n';
        IF position(a IN d) = 0 THEN RAISE EXCEPTION 'patokan process_approval_action tidak ketemu'; END IF;
