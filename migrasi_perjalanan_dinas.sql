-- Check-in GPS opsional oleh pemohon (1x per hari per PD).
CREATE OR REPLACE FUNCTION public.checkin_perjalanan_dinas(p_token text, p_id bigint, p_lat double precision DEFAULT NULL, p_lng double precision DEFAULT NULL, p_akurasi double precision DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
    v_emp bigint := operational.badge_sesi(p_token);
    v_req record;
BEGIN
    IF v_emp IS NULL THEN
        RETURN jsonb_build_object('status', 'SESSION_EXPIRED', 'message', 'Sesi Badge habis. Buka ulang Badge dan masukkan PIN.');
    END IF;
    SELECT p.* INTO v_req FROM public.pengajuan_ijin_lembur_tbl p
    JOIN public."karyawanTbl" k ON UPPER(btrim(k."QrCodeId")) = UPPER(btrim(p.qrcodeid))
    WHERE p.id = p_id AND p.tipe = 'PERJALANAN_DINAS' AND k."Id" = v_emp;
    IF NOT FOUND THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Perjalanan dinas tidak ditemukan.');
    END IF;
    IF v_req.status <> 'APPROVED' OR public.pd_hari_ini() NOT BETWEEN v_req.tanggal_mulai AND v_req.tanggal_selesai THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Check-in hanya bisa pada tanggal dinas yang sudah disetujui.');
    END IF;
    IF EXISTS (SELECT 1 FROM public.perjalanan_dinas_log WHERE pengajuan_id = p_id AND sumber = 'CHECKIN_PEMOHON'
               AND (waktu AT TIME ZONE 'Asia/Makassar')::date = public.pd_hari_ini()) THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Anda sudah check-in hari ini.');
    END IF;
    INSERT INTO public.perjalanan_dinas_log (pengajuan_id, sumber, nama, lat, lng, akurasi_m)
    VALUES (p_id, 'CHECKIN_PEMOHON', v_req.nama_pemohon, p_lat, p_lng, p_akurasi);
    RETURN jsonb_build_object('status', 'SUCCESS', 'message',
        CASE WHEN p_lat IS NULL THEN 'Check-in tercatat (tanpa GPS).' ELSE 'Check-in lokasi dinas tercatat.' END);
END;
$$;
REVOKE ALL ON FUNCTION public.checkin_perjalanan_dinas(text, bigint, double precision, double precision, double precision) FROM PUBLIC;
