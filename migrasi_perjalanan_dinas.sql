            || E'                v_jam_regular_menit := ROUND(v_jam_normal * 60);\n'
            || E'                v_jam_lembur_reguler_menit := 0;\n'
            || E'                v_jam_aktual_menit := v_jam_regular_menit;\n'
            || E'            END IF;\n' || a);
        EXECUTE d;
    END IF;

    -- 8d. proses_payroll_bulanan: hari PD (APPROVED) tanpa scan masuk ikut JumlahHariHadir.
    --     Tidak menambah jam lembur otomatis. Tarif dinas TIDAK masuk payroll (dicatat saja).
    d := pg_get_functiondef('public.proses_payroll_bulanan(integer,integer,text)'::regprocedure);
    IF position('PERJALANAN_DINAS' IN d) = 0 THEN
        a := E'        v_jam_man_kerja := 0; v_jam_man_off := 0;\n';
        IF position(a IN d) = 0 THEN RAISE EXCEPTION 'patokan proses_payroll_bulanan tidak ketemu'; END IF;
        d := replace(d, a,
            E'        -- Hari Perjalanan Dinas (APPROVED) dihitung hadir walau tidak scan absen.\n'
            || E'        v_hari_hadir := v_hari_hadir + COALESCE((\n'
            || E'            SELECT COUNT(DISTINCT g.tgl)::INT\n'
            || E'            FROM pengajuan_ijin_lembur_tbl pd\n'
            || E'            CROSS JOIN LATERAL generate_series(GREATEST(pd.tanggal_mulai, v_periode_awal), LEAST(pd.tanggal_selesai, v_periode_akhir), ''1 day''::interval) AS g(tgl)\n'
