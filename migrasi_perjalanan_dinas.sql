-- =====================================================================
-- Ijin Perjalanan Dinas (PD) di Digital Badge
-- =====================================================================
-- Alur:
--   1. Pemohon ajukan dari Badge (login PIN -> token sesi): tanggal berangkat &
--      kembali, tujuan, keperluan, transportasi, perkiraan jarak (km).
--   2. Approval atasan berjenjang (AuthorizedById, maks 3 level, level Direktur
--      auto) -- SAMA dengan Cuti/Off.
--   3. Setelah atasan selesai -> Verifikasi HR (hrcheck_target_role, sama dengan
--      Cuti). Beda dengan Cuti: HR di AKHIR, bukan di awal.
--   4. APPROVED -> terbit kode voucher (QR). QR dibuka HP di tujuan lewat
--      verifikasi-dinas.html -> cek keaslian + opsional catat "sudah tiba".
--   5. Hari-hari dinas otomatis dihitung HADIR (timesheet & JumlahHariHadir
--      payroll), tanpa lembur otomatis. Check-in GPS dari Badge opsional.
--   6. Tarif dinas (uang harian & penginapan) diambil dari tarifPerjalananDinasTbl
--      berdasarkan Grade karyawan + jarak -> DICATAT saja (snapshot), belum
--      masuk payroll.
--
-- Data rinci PD (biaya, kode voucher) disimpan di tabel terpisah yang TIDAK bisa
-- dibaca anon, karena pengajuan_ijin_lembur_tbl punya policy baca publik.
-- Fungsi lama yang perlu tahu PD (process_approval_action, side effects,
-- timesheet, payroll, validasi tanggal) ditambal lewat DO-block: definisi live
-- diambil, disisipi baris PD, gagal keras kalau patokan teks tidak ketemu.
-- =====================================================================

