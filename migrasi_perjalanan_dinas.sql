-- 7. Antrean approval (Badge & portal): tambah kolom rincian PD di belakang.
--    Tipe kembalian berubah -> DROP lalu CREATE.
-- ---------------------------------------------------------------------
DROP FUNCTION IF EXISTS public.get_pending_ijin_lembur_approvals_by_qrcode(text);
CREATE FUNCTION public.get_pending_ijin_lembur_approvals_by_qrcode(p_qrcode text)
 RETURNS TABLE(id bigint, qrcodeid text, nama_pemohon text, kualifikasi text, tipe text, tanggal date, alasan text, durasi_jam numeric, lokasi text, status text, total_levels integer, current_level integer, required_action text, created_at timestamp with time zone, kategori_ijin text, jenis_cuti text, tanggal_mulai date, tanggal_selesai date, jumlah_hari integer, peringatan_kuota text, tanggal_mulai_awal date, tanggal_selesai_awal date, tanggal_diubah_oleh text, tanggal_diubah_catatan text, rencana_jam text,
               pd_transportasi text, pd_jarak_km numeric, pd_grade text, pd_estimasi_biaya numeric, pd_atasan_selesai text)
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_author_tokens TEXT[];
    v_my_id BIGINT;
BEGIN
    -- Tiket cek HR dikirim berdasarkan AUTHOR saja (token dipisah koma, dicocokkan persis).
    -- Author dibaca dari paswordTbl (diisi lewat portal) dan karyawanTbl.
    SELECT k."Id",
           COALESCE((
             SELECT array_agg(DISTINCT UPPER(TRIM(t)))
             FROM unnest(string_to_array(COALESCE(p."Author", '') || ',' || COALESCE(k."Author", ''), ',')) AS t
             WHERE TRIM(t) <> ''
           ), ARRAY[]::TEXT[])
    INTO v_my_id, v_author_tokens
    FROM "karyawanTbl" k
    LEFT JOIN "paswordTbl" p ON p."Id" = k."Id"
    WHERE UPPER(TRIM(k."QrCodeId")) = UPPER(TRIM(p_qrcode))
    LIMIT 1;

    RETURN QUERY
    SELECT
        p.id, p.qrcodeid, p.nama_pemohon, p.kualifikasi, p.tipe, p.tanggal, p.alasan, p.durasi_jam, p.lokasi,
        p.status, p.total_levels, p.current_level,
        CASE
            WHEN p.current_level = 0 THEN 'HR_CHECK'
            WHEN p.current_level = p.total_levels THEN 'APPROVE'
            WHEN p.current_level = 1 THEN 'PROPOSE'
            WHEN p.current_level = 2 THEN 'REVIEW'
            ELSE 'APPROVE'
        END AS required_action,
        p.created_at,
        p.kategori_ijin,
        CASE WHEN p.tipe IN ('CUTI', 'OFF') THEN p.jenis_cuti END,
        p.tanggal_mulai, p.tanggal_selesai, p.jumlah_hari,
        CASE WHEN p.tipe = 'OFF' AND p.jenis_cuti = 'OFF_ROTASI'
             THEN off_rotasi_kuota_info(p.qrcodeid, p.tanggal_mulai, p.tanggal_selesai, p.id)->>'peringatan' END,
        p.tanggal_mulai_awal, p.tanggal_selesai_awal, p.tanggal_diubah_oleh, p.tanggal_diubah_catatan,
        p.rencana_jam,
        d.transportasi, d.jarak_km, d.grade, d.estimasi_biaya,
        CASE WHEN p.tipe = 'PERJALANAN_DINAS' AND p.current_level = 0
             THEN NULLIF(concat_ws(', ', p.level1_by, p.level2_by, p.level3_by), '') END
    FROM pengajuan_ijin_lembur_tbl p
    LEFT JOIN perjalanan_dinas_detail d ON d.pengajuan_id = p.id
    WHERE p.status NOT IN ('APPROVED', 'REJECTED')
      AND (
        (p.current_level = 0 AND UPPER(TRIM(p.hrcheck_target_role)) = ANY(COALESCE(v_author_tokens, ARRAY[]::TEXT[])))
        OR (p.current_level = 1 AND v_my_id IS NOT NULL AND p.level1_approver_id = v_my_id)
        OR (p.current_level = 2 AND v_my_id IS NOT NULL AND p.level2_approver_id = v_my_id)
        OR (p.current_level = 3 AND v_my_id IS NOT NULL AND p.level3_approver_id = v_my_id)
      )
    ORDER BY p.id DESC;
END;
$function$;
