ALTER TABLE public."karyawanTbl" ADD COLUMN IF NOT EXISTS "Grade" text;
COMMENT ON COLUMN public."karyawanTbl"."Grade" IS 'Grade karyawan untuk tarif perjalanan dinas (cocok dengan tarifPerjalananDinasTbl.Grade).';

CREATE TABLE IF NOT EXISTS public."tarifPerjalananDinasTbl" (
    "Id"             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Grade"          text    NOT NULL,
    "JarakMinKm"     numeric NOT NULL DEFAULT 0,
    "JarakMaxKm"     numeric,               -- NULL = tanpa batas atas
    "UangHarian"     numeric NOT NULL DEFAULT 0,  -- per hari
    "UangPenginapan" numeric NOT NULL DEFAULT 0,  -- per malam
    "Keterangan"     text,
    "IsAktif"        boolean NOT NULL DEFAULT true,
    "CreatedAt"      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT tarif_pd_jarak_chk CHECK ("JarakMinKm" >= 0 AND ("JarakMaxKm" IS NULL OR "JarakMaxKm" >= "JarakMinKm"))
);
COMMENT ON TABLE public."tarifPerjalananDinasTbl" IS 'Tarif perjalanan dinas per Grade dan rentang jarak (km). Jarak dicocokkan JarakMinKm <= jarak < JarakMaxKm.';
ALTER TABLE public."tarifPerjalananDinasTbl" ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS baca_publik ON public."tarifPerjalananDinasTbl";
CREATE POLICY baca_publik ON public."tarifPerjalananDinasTbl" FOR SELECT TO anon, authenticated USING (true);
GRANT SELECT ON public."tarifPerjalananDinasTbl" TO anon, authenticated;

CREATE TABLE IF NOT EXISTS public.perjalanan_dinas_detail (
    pengajuan_id     bigint PRIMARY KEY REFERENCES public.pengajuan_ijin_lembur_tbl(id) ON DELETE CASCADE,
    tujuan           text    NOT NULL,
    transportasi     text,
    jarak_km         numeric,
    grade            text,
    tarif_id         bigint REFERENCES public."tarifPerjalananDinasTbl"("Id") ON DELETE SET NULL,
    uang_harian      numeric,
    uang_penginapan  numeric,
    estimasi_biaya   numeric,
    kode_verifikasi  text UNIQUE,
    created_at       timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.perjalanan_dinas_detail ENABLE ROW LEVEL SECURITY;  -- tanpa policy: cuma lewat RPC
REVOKE ALL ON public.perjalanan_dinas_detail FROM anon, authenticated;

CREATE TABLE IF NOT EXISTS public.perjalanan_dinas_log (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pengajuan_id  bigint NOT NULL REFERENCES public.pengajuan_ijin_lembur_tbl(id) ON DELETE CASCADE,
    sumber        text   NOT NULL CHECK (sumber IN ('CHECKIN_PEMOHON', 'KONFIRMASI_TUJUAN')),
    nama          text,
    catatan       text,
    lat           double precision,
    lng           double precision,
    akurasi_m     double precision,
    waktu         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS perjalanan_dinas_log_pengajuan_idx ON public.perjalanan_dinas_log (pengajuan_id);
ALTER TABLE public.perjalanan_dinas_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.perjalanan_dinas_log FROM anon, authenticated;

ALTER TABLE public.pengajuan_ijin_lembur_tbl DROP CONSTRAINT IF EXISTS pengajuan_ijin_lembur_tbl_tipe_check;
