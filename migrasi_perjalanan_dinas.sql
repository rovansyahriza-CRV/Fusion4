-- ---------------------------------------------------------------------
-- 2. Helper
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.pd_hari_ini()
RETURNS date LANGUAGE sql STABLE SET search_path TO '' AS
$$ SELECT (now() AT TIME ZONE 'Asia/Makassar')::date $$;

-- Tarif untuk grade + jarak (NULL kalau grade kosong / tidak ada baris yang cocok).
CREATE OR REPLACE FUNCTION public.pd_cari_tarif(p_grade text, p_jarak numeric)
RETURNS public."tarifPerjalananDinasTbl"
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS
$$
    SELECT t.* FROM public."tarifPerjalananDinasTbl" t
    WHERE t."IsAktif"
      AND NULLIF(btrim(p_grade), '') IS NOT NULL
      AND UPPER(btrim(t."Grade")) = UPPER(btrim(p_grade))
      AND COALESCE(p_jarak, 0) >= t."JarakMinKm"
      AND (t."JarakMaxKm" IS NULL OR COALESCE(p_jarak, 0) < t."JarakMaxKm")
    ORDER BY t."JarakMinKm" DESC, t."Id" DESC
    LIMIT 1
$$;

-- ---------------------------------------------------------------------
-- 3. Submit dari Badge (token sesi badge_login)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.submit_perjalanan_dinas(
    p_token        text,
    p_tgl_mulai    date,
    p_tgl_selesai  date,
    p_tujuan       text,
    p_keperluan    text,
    p_transportasi text DEFAULT NULL,
    p_jarak_km     numeric DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
    v_emp     bigint := operational.badge_sesi(p_token);
    v_k       record;
    v_rec     record;
    v_hari    int;
    v_tarif   public."tarifPerjalananDinasTbl";
    v_estimasi numeric;
    v_new_id  bigint;
    v_total_levels int := 1;
    v_l1_label text := 'Direktur (Auto-Approve)'; v_l1_auto boolean := true;  v_l1_approver bigint;
    v_l2_label text; v_l2_auto boolean := false; v_l2_approver bigint;
    v_l3_label text; v_l3_auto boolean := false; v_l3_approver bigint;
    v_langsung_hr boolean;
BEGIN
    IF v_emp IS NULL THEN
        RETURN jsonb_build_object('status', 'SESSION_EXPIRED', 'message', 'Sesi Badge habis. Buka ulang Badge dan masukkan PIN.');
    END IF;
    IF p_tgl_mulai IS NULL OR p_tgl_selesai IS NULL THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Tanggal berangkat dan kembali wajib diisi.');
    END IF;
    IF p_tgl_selesai < p_tgl_mulai THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Tanggal kembali tidak boleh lebih awal dari tanggal berangkat.');
    END IF;
    IF p_tgl_mulai < public.pd_hari_ini() - 3 THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Tanggal berangkat paling lambat 3 hari ke belakang.');
    END IF;
    v_hari := (p_tgl_selesai - p_tgl_mulai) + 1;
    IF v_hari > 60 THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Perjalanan dinas maksimal 60 hari per pengajuan.');
    END IF;
    IF NULLIF(btrim(p_tujuan), '') IS NULL THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Tujuan perjalanan wajib diisi.');
    END IF;
    IF NULLIF(btrim(p_keperluan), '') IS NULL THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Keperluan dinas wajib diisi.');
    END IF;
    IF p_jarak_km IS NOT NULL AND (p_jarak_km < 0 OR p_jarak_km > 20000) THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Jarak tidak valid.');
    END IF;

    SELECT "Id", "QrCodeId", "NamaPersonnel", "Kualifikasi", "AuthorizedById", "Grade"
    INTO v_k FROM public."karyawanTbl" WHERE "Id" = v_emp;

    -- Bentrok dengan Cuti / Off / Perjalanan Dinas lain yang belum ditolak.
    SELECT p.tipe, p.tanggal_mulai, p.tanggal_selesai INTO v_rec
    FROM public.pengajuan_ijin_lembur_tbl p
    WHERE UPPER(btrim(p.qrcodeid)) = UPPER(btrim(v_k."QrCodeId"))
      AND p.tipe IN ('CUTI', 'OFF', 'PERJALANAN_DINAS')
      AND p.status <> 'REJECTED'
      AND p.tanggal_mulai <= p_tgl_selesai
      AND COALESCE(p.tanggal_selesai, p.tanggal_mulai) >= p_tgl_mulai
    LIMIT 1;
    IF FOUND THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message',
            'Tanggal bentrok dengan ' || INITCAP(REPLACE(v_rec.tipe, '_', ' ')) || ' '
            || TO_CHAR(v_rec.tanggal_mulai, 'DD/MM/YYYY') || ' s/d '
            || TO_CHAR(COALESCE(v_rec.tanggal_selesai, v_rec.tanggal_mulai), 'DD/MM/YYYY') || '.');
    END IF;

    -- Rantai atasan (AuthorizedById), pola sama dengan submit_pengajuan_cuti.
    IF v_k."AuthorizedById" IS NOT NULL THEN
        SELECT "Id", "NamaPersonnel", "Kualifikasi", "AuthorizedById" INTO v_rec
        FROM public."karyawanTbl" WHERE "Id" = v_k."AuthorizedById";
        IF FOUND THEN
            v_l1_approver := v_rec."Id";
            v_l1_label := v_rec."NamaPersonnel" || ' (' || COALESCE(v_rec."Kualifikasi", '-') || ')';
            v_l1_auto := (v_rec."Kualifikasi" ILIKE 'Direktur%');
            v_total_levels := 1;
            IF NOT v_l1_auto AND v_rec."AuthorizedById" IS NOT NULL THEN
                SELECT "Id", "NamaPersonnel", "Kualifikasi", "AuthorizedById" INTO v_rec
                FROM public."karyawanTbl" WHERE "Id" = v_rec."AuthorizedById";
                IF FOUND THEN
                    v_l2_approver := v_rec."Id";
                    v_l2_label := v_rec."NamaPersonnel" || ' (' || COALESCE(v_rec."Kualifikasi", '-') || ')';
                    v_l2_auto := (v_rec."Kualifikasi" ILIKE 'Direktur%');
                    v_total_levels := 2;
                    IF NOT v_l2_auto AND v_rec."AuthorizedById" IS NOT NULL THEN
                        SELECT "Id", "NamaPersonnel", "Kualifikasi", "AuthorizedById" INTO v_rec
                        FROM public."karyawanTbl" WHERE "Id" = v_rec."AuthorizedById";
                        IF FOUND THEN
                            v_l3_approver := v_rec."Id";
                            v_l3_label := v_rec."NamaPersonnel" || ' (' || COALESCE(v_rec."Kualifikasi", '-') || ')';
                            v_l3_auto := (v_rec."Kualifikasi" ILIKE 'Direktur%');
                            v_total_levels := 3;
                        END IF;
                    END IF;
                END IF;
            END IF;
        END IF;
    END IF;

    -- Level 1 tanpa approver manusia (tidak ada atasan / atasannya Direktur) -> langsung Verifikasi HR.
    v_langsung_hr := (v_l1_approver IS NULL OR v_l1_auto);

    v_tarif := public.pd_cari_tarif(v_k."Grade", p_jarak_km);
    IF v_tarif."Id" IS NOT NULL THEN
        v_estimasi := v_tarif."UangHarian" * v_hari + v_tarif."UangPenginapan" * GREATEST(v_hari - 1, 0);
    END IF;

    INSERT INTO public.pengajuan_ijin_lembur_tbl (
        qrcodeid, nama_pemohon, kualifikasi, tipe, tanggal,
        tanggal_mulai, tanggal_selesai, jumlah_hari, lokasi, alasan,
        status, total_levels, current_level, hrcheck_target_role,
        level1_target_role, level1_approver_id, level1_is_auto,
        level1_by, level1_at, level1_action, level1_notes,
        level2_target_role, level2_approver_id, level2_is_auto,
        level3_target_role, level3_approver_id, level3_is_auto
    ) VALUES (
        UPPER(btrim(v_k."QrCodeId")), v_k."NamaPersonnel", v_k."Kualifikasi", 'PERJALANAN_DINAS', p_tgl_mulai,
        p_tgl_mulai, p_tgl_selesai, v_hari, btrim(p_tujuan), btrim(p_keperluan),
        CASE WHEN v_langsung_hr THEN 'PENDING_HR_CHECK' ELSE 'PENDING_PROPOSE' END,
        v_total_levels, CASE WHEN v_langsung_hr THEN 0 ELSE 1 END, 'HR Operations / HR Admin',
        v_l1_label, v_l1_approver, v_l1_auto,
        CASE WHEN v_langsung_hr THEN 'Sistem (Auto-Approve Direktur)' END,
        CASE WHEN v_langsung_hr THEN now() END,
        CASE WHEN v_langsung_hr THEN 'APPROVED' END,
        CASE WHEN v_langsung_hr THEN 'Auto-approved -- level Direktur bersifat informasi saja.' END,
        v_l2_label, v_l2_approver, v_l2_auto,
        v_l3_label, v_l3_approver, v_l3_auto
    ) RETURNING id INTO v_new_id;

    INSERT INTO public.perjalanan_dinas_detail (
        pengajuan_id, tujuan, transportasi, jarak_km, grade, tarif_id,
        uang_harian, uang_penginapan, estimasi_biaya
    ) VALUES (
        v_new_id, btrim(p_tujuan), NULLIF(btrim(p_transportasi), ''), p_jarak_km, NULLIF(btrim(v_k."Grade"), ''), v_tarif."Id",
        v_tarif."UangHarian", v_tarif."UangPenginapan", v_estimasi
    );

    RETURN jsonb_build_object(
        'status', 'SUCCESS',
        'id', v_new_id,
        'jumlahHari', v_hari,
        'estimasiBiaya', v_estimasi,
        'message', 'Pengajuan Perjalanan Dinas (' || v_hari || ' hari) terkirim. '
            || CASE WHEN v_langsung_hr THEN 'Menunggu verifikasi HR.' ELSE 'Menunggu approval atasan, lalu verifikasi HR.' END
            || CASE WHEN v_tarif."Id" IS NULL THEN ' (Tarif dinas belum ditemukan untuk Grade/jarak Anda -- HR akan melengkapi.)' ELSE '' END
    );
END;
$$;
REVOKE ALL ON FUNCTION public.submit_perjalanan_dinas(text, date, date, text, text, text, numeric) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.submit_perjalanan_dinas(text, date, date, text, text, text, numeric) TO anon, authenticated, service_role;

-- ---------------------------------------------------------------------
-- 4. Approval PD: atasan (level 1..N) dulu, lalu Verifikasi HR (level 0).
--    Dipanggil dari process_approval_action (Badge & portal pakai RPC itu).
--    Beda dengan tipe lain: approver dicek harus orang yang memang dituju.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.proses_perjalanan_dinas_inti(p_request_id bigint, p_user_qrcode text, p_action text, p_catatan text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
    v_req     public.pengajuan_ijin_lembur_tbl;
    v_me      record;
    v_tokens  text[];
    v_oleh    text;
    v_lv      int;
    v_next    int;
    v_next_auto boolean;
    v_aksi    text;
    v_action  text := UPPER(btrim(COALESCE(p_action, '')));
BEGIN
    SELECT * INTO v_req FROM public.pengajuan_ijin_lembur_tbl WHERE id = p_request_id FOR UPDATE;
    IF NOT FOUND OR v_req.tipe <> 'PERJALANAN_DINAS' THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Pengajuan perjalanan dinas tidak ditemukan.');
    END IF;
    IF v_req.status IN ('APPROVED', 'REJECTED') THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Pengajuan sudah berstatus ' || v_req.status || ' dan tidak dapat diubah.');
    END IF;

    SELECT k."Id", k."NamaPersonnel", k."Kualifikasi", NULLIF(btrim(k."Author"), '') AS author_code,
           COALESCE((
               SELECT array_agg(DISTINCT UPPER(btrim(t)))
               FROM unnest(string_to_array(COALESCE(pw."Author", '') || ',' || COALESCE(k."Author", ''), ',')) AS t
               WHERE btrim(t) <> ''
           ), ARRAY[]::text[]) AS tokens
    INTO v_me
    FROM public."karyawanTbl" k
    LEFT JOIN public."paswordTbl" pw ON pw."Id" = k."Id"
    WHERE UPPER(btrim(k."QrCodeId")) = UPPER(btrim(p_user_qrcode))
    LIMIT 1;
    IF v_me."Id" IS NULL THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Identitas otorisator tidak valid.');
    END IF;
    v_tokens := v_me.tokens;
    v_oleh := v_me."NamaPersonnel" || ' (' || COALESCE(v_me.author_code, v_me."Kualifikasi", '-') || ')';
    v_lv := v_req.current_level;

    -- Wewenang tahap ini
    IF v_lv = 0 THEN
        IF NOT (UPPER(btrim(COALESCE(v_req.hrcheck_target_role, ''))) = ANY (v_tokens)) THEN
            RETURN jsonb_build_object('status', 'ERROR', 'message', 'Tahap ini menunggu Verifikasi HR. Akun Anda bukan verifikator HR.');
        END IF;
    ELSIF (v_lv = 1 AND v_req.level1_approver_id IS DISTINCT FROM v_me."Id")
       OR (v_lv = 2 AND v_req.level2_approver_id IS DISTINCT FROM v_me."Id")
       OR (v_lv = 3 AND v_req.level3_approver_id IS DISTINCT FROM v_me."Id") THEN
        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Anda bukan approver untuk tahap ini.');
    END IF;

    IF v_action = 'REJECT' THEN
        UPDATE public.pengajuan_ijin_lembur_tbl
        SET status = 'REJECTED', reject_reason = p_catatan, rejected_by = v_oleh, rejected_at = now(), updated_at = now()
        WHERE id = p_request_id;
        RETURN jsonb_build_object('status', 'SUCCESS', 'message', 'Pengajuan perjalanan dinas ditolak.');
    END IF;

    -- Tahap akhir: Verifikasi HR -> APPROVED
    IF v_lv = 0 THEN
        UPDATE public.pengajuan_ijin_lembur_tbl
        SET status = 'APPROVED', hrcheck_by = v_oleh, hrcheck_at = now(), hrcheck_action = 'APPROVED',
            hrcheck_notes = p_catatan, updated_at = now()
        WHERE id = p_request_id;
        PERFORM public.apply_pengajuan_final_side_effects(p_request_id);
        RETURN jsonb_build_object('status', 'SUCCESS', 'message', 'Perjalanan dinas terverifikasi HR dan resmi disetujui. Voucher QR terbit di Badge pemohon.');
    END IF;

    -- Tahap atasan
    v_aksi := CASE WHEN v_lv = v_req.total_levels THEN 'APPROVED' WHEN v_lv = 1 THEN 'PROPOSE' WHEN v_lv = 2 THEN 'REVIEW' ELSE 'APPROVED' END;
    EXECUTE format('UPDATE public.pengajuan_ijin_lembur_tbl SET %I = $1, %I = now(), %I = $2, %I = $3, updated_at = now() WHERE id = $4',
                   'level' || v_lv || '_by', 'level' || v_lv || '_at', 'level' || v_lv || '_action', 'level' || v_lv || '_notes')
        USING v_oleh, v_aksi, p_catatan, p_request_id;

    v_next := v_lv + 1;
    v_next_auto := CASE v_next WHEN 2 THEN v_req.level2_is_auto WHEN 3 THEN v_req.level3_is_auto ELSE false END;

    IF v_next <= v_req.total_levels AND NOT COALESCE(v_next_auto, false) THEN
        UPDATE public.pengajuan_ijin_lembur_tbl SET status = 'PROPOSED', current_level = v_next, updated_at = now() WHERE id = p_request_id;
        RETURN jsonb_build_object('status', 'SUCCESS', 'message', 'Pengajuan diteruskan ke approval Level ' || v_next || '.');
    END IF;

    IF v_next <= v_req.total_levels THEN  -- level berikutnya Direktur: informasi saja
        EXECUTE format('UPDATE public.pengajuan_ijin_lembur_tbl SET %I = $1, %I = now(), %I = ''APPROVED'', %I = $2 WHERE id = $3',
                       'level' || v_next || '_by', 'level' || v_next || '_at', 'level' || v_next || '_action', 'level' || v_next || '_notes')
            USING 'Sistem (Auto-Approve Direktur)', 'Auto-approved -- level Direktur bersifat informasi saja.', p_request_id;
    END IF;

    UPDATE public.pengajuan_ijin_lembur_tbl SET status = 'PENDING_HR_CHECK', current_level = 0, updated_at = now() WHERE id = p_request_id;
    RETURN jsonb_build_object('status', 'SUCCESS', 'message', 'Approval atasan selesai. Lanjut Verifikasi HR.');
END;
$$;
REVOKE ALL ON FUNCTION public.proses_perjalanan_dinas_inti(bigint, text, text, text) FROM PUBLIC, anon, authenticated;

-- ---------------------------------------------------------------------
-- 5. Daftar PD milik pemohon (Badge) + voucher QR
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.get_perjalanan_dinas_saya(p_token text)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
    v_emp bigint := operational.badge_sesi(p_token);
    v_qr  text;
BEGIN
    IF v_emp IS NULL THEN
        RETURN jsonb_build_object('status', 'SESSION_EXPIRED', 'items', '[]'::jsonb);
    END IF;
    SELECT UPPER(btrim("QrCodeId")) INTO v_qr FROM public."karyawanTbl" WHERE "Id" = v_emp;

    RETURN jsonb_build_object('status', 'OK', 'items', COALESCE((
        SELECT jsonb_agg(x ORDER BY (x->>'id')::bigint DESC) FROM (
            SELECT jsonb_build_object(
                'id', p.id,
                'status', p.status,
                'tahap', CASE
                    WHEN p.status = 'APPROVED' THEN 'Disetujui'
                    WHEN p.status = 'REJECTED' THEN 'Ditolak' || COALESCE(' oleh ' || p.rejected_by, '') || COALESCE(': ' || NULLIF(p.reject_reason, ''), '')
                    WHEN p.current_level = 0 THEN 'Menunggu Verifikasi HR'
                    ELSE 'Menunggu approval Level ' || p.current_level || '/' || p.total_levels || ' (' || COALESCE(
                        CASE p.current_level WHEN 1 THEN p.level1_target_role WHEN 2 THEN p.level2_target_role ELSE p.level3_target_role END, '-') || ')'
                END,
                'tanggalMulai', p.tanggal_mulai,
                'tanggalSelesai', p.tanggal_selesai,
                'jumlahHari', p.jumlah_hari,
                'tujuan', d.tujuan,
                'keperluan', p.alasan,
                'transportasi', d.transportasi,
                'jarakKm', d.jarak_km,
                'grade', d.grade,
                'estimasiBiaya', d.estimasi_biaya,
                'kode', CASE WHEN p.status = 'APPROVED' THEN d.kode_verifikasi END,
                'berlakuHariIni', (p.status = 'APPROVED' AND public.pd_hari_ini() BETWEEN p.tanggal_mulai AND p.tanggal_selesai),
                'jumlahCheckin', (SELECT count(*) FROM public.perjalanan_dinas_log l WHERE l.pengajuan_id = p.id AND l.sumber = 'CHECKIN_PEMOHON'),
                'checkinHariIni', EXISTS (SELECT 1 FROM public.perjalanan_dinas_log l WHERE l.pengajuan_id = p.id AND l.sumber = 'CHECKIN_PEMOHON'
                                          AND (l.waktu AT TIME ZONE 'Asia/Makassar')::date = public.pd_hari_ini()),
                'jumlahKonfirmasiTujuan', (SELECT count(*) FROM public.perjalanan_dinas_log l WHERE l.pengajuan_id = p.id AND l.sumber = 'KONFIRMASI_TUJUAN')
            ) AS x
            FROM public.pengajuan_ijin_lembur_tbl p
            LEFT JOIN public.perjalanan_dinas_detail d ON d.pengajuan_id = p.id
            WHERE p.tipe = 'PERJALANAN_DINAS'
              AND UPPER(btrim(p.qrcodeid)) = v_qr
              AND (p.status NOT IN ('APPROVED', 'REJECTED') OR p.tanggal_selesai >= public.pd_hari_ini() - 7)
            ORDER BY p.id DESC
            LIMIT 20
        ) s
    ), '[]'::jsonb));
END;
$$;
