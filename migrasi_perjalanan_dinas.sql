        d := replace(d, a, E'      AND "tipe" IN (''CUTI'', ''OFF'', ''PERJALANAN_DINAS'')\n');
        d := replace(d, 'INITCAP(v_bentrok.tipe)', 'INITCAP(REPLACE(v_bentrok.tipe, ''_'', '' ''))');
        EXECUTE d;
    END IF;
END
