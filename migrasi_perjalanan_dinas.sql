    d := pg_get_functiondef('public.apply_pengajuan_final_side_effects(bigint)'::regprocedure);
    IF position('PERJALANAN_DINAS' IN d) = 0 THEN
        a := E'    ELSIF v_req.tipe = ''OFF'' THEN\n';
        IF position(a IN d) = 0 THEN RAISE EXCEPTION 'patokan apply_pengajuan_final_side_effects tidak ketemu'; END IF;
        d := replace(d, a,
            E'    ELSIF v_req.tipe = ''PERJALANAN_DINAS'' THEN\n'
            || E'        -- Kode voucher QR (diverifikasi di verifikasi-dinas.html). Hari dinas dihitung hadir\n'
            || E'        -- langsung di get_timesheet_bulanan & proses_payroll_bulanan, bukan lewat absensiTbl.\n'
            || E'        UPDATE public.perjalanan_dinas_detail\n'
            || E'        SET kode_verifikasi = COALESCE(kode_verifikasi, ''PD-'' || UPPER(SUBSTRING(REPLACE(gen_random_uuid()::TEXT, ''-'', ''''), 1, 12)))\n'
            || E'        WHERE pengajuan_id = p_request_id;\n\n' || a);
        EXECUTE d;
    END IF;

    -- 8c. get_timesheet_bulanan: hari PD = status DINAS, jam regular penuh di hari kerja.
    d := pg_get_functiondef('public.get_timesheet_bulanan(bigint,integer,integer)'::regprocedure);
    IF position('PERJALANAN_DINAS' IN d) = 0 THEN
        a := E'          AND tipe IN (''CUTI'', ''IJIN'')\n';
        IF position(a IN d) = 0 THEN RAISE EXCEPTION 'patokan timesheet (tipe) tidak ketemu'; END IF;
        d := replace(d, a, E'          AND tipe IN (''CUTI'', ''IJIN'', ''PERJALANAN_DINAS'')\n');

        a := E'        ELSIF v_absen."Id" IS NOT NULL THEN\n            v_status := ''PARSIAL'';\n';
        IF position(a IN d) = 0 THEN RAISE EXCEPTION 'patokan timesheet (PARSIAL) tidak ketemu'; END IF;
        d := replace(d, a,
            E'        ELSIF v_izin.id IS NOT NULL AND v_izin.tipe = ''PERJALANAN_DINAS'' THEN\n'
            || E'            -- Perjalanan Dinas: dihitung hadir (jam normal di hari kerja), walau scan absen tidak lengkap.\n'
            || E'            v_status := ''DINAS'';\n'
            || E'            v_keterangan := ''Perjalanan Dinas'' || COALESCE('' ke '' || NULLIF(v_izin.lokasi, ''''), '''');\n'
