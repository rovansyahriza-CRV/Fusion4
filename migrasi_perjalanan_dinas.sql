        RETURN jsonb_build_object('status', 'ERROR', 'message', 'Batas konfirmasi untuk perjalanan ini sudah tercapai.');
    END IF;
    INSERT INTO public.perjalanan_dinas_log (pengajuan_id, sumber, nama, catatan, lat, lng, akurasi_m)
    VALUES (v.id, 'KONFIRMASI_TUJUAN', left(btrim(p_nama), 80), left(NULLIF(btrim(p_catatan), ''), 300), p_lat, p_lng, p_akurasi);
    RETURN jsonb_build_object('status', 'SUCCESS', 'message', 'Kedatangan personel tercatat. Terima kasih.');
